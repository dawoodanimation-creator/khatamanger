import type { Customer } from '../models/customer';
import type { HistoryEntry } from './balance';
import { money } from './money';
import { localDate } from './dates';

export function printCustomerStatement(
  customer: Customer,
  history: HistoryEntry[],
  currentBalance: number,
  currencyLabel: string,
  isUrdu: boolean,
): boolean {
  try {
    const printWindow = window.open('', '_blank');
    if (!printWindow) return false;

    const totalCredit = history.reduce((sum, h) => sum + (h.transaction.kind === 'credit' ? h.transaction.amountPaisa : 0), 0);
    const totalPayment = history.reduce((sum, h) => sum + (h.transaction.kind === 'payment' ? h.transaction.amountPaisa : 0), 0);

    const html = `<!DOCTYPE html>
<html lang="${isUrdu ? 'ur' : 'en'}" dir="${isUrdu ? 'rtl' : 'ltr'}">
<head>
  <meta charset="utf-8">
  <title>${customer.name} - Statement</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; padding: 24px; color: #111; max-width: 650px; margin: 0 auto; }
    .header { text-align: center; border-bottom: 2px solid #086b57; padding-bottom: 12px; margin-bottom: 20px; }
    .header h1 { margin: 0; color: #086b57; font-size: 24px; }
    .header p { margin: 4px 0 0; color: #666; font-size: 14px; }
    .customer-box { background: #f4f6f5; padding: 12px 16px; border-radius: 8px; margin-bottom: 20px; display: flex; justify-content: space-between; }
    .customer-box div p { margin: 4px 0; font-size: 14px; }
    .balance-box { text-align: end; }
    .balance-box strong { font-size: 20px; color: ${currentBalance > 0 ? '#b91c1c' : '#15803d'}; }
    table { width: 100%; border-collapse: collapse; margin-bottom: 24px; font-size: 13px; }
    th, td { border: 1px solid #ddd; padding: 8px 10px; text-align: ${isUrdu ? 'right' : 'left'}; }
    th { background: #086b57; color: #fff; }
    .amount-credit { color: #b91c1c; font-weight: bold; }
    .amount-payment { color: #15803d; font-weight: bold; }
    .summary-table { width: 100%; margin-top: 10px; border-top: 2px solid #086b57; padding-top: 10px; display: flex; justify-content: space-between; font-size: 14px; }
    .footer { text-align: center; margin-top: 30px; font-size: 12px; color: #888; border-top: 1px solid #eee; padding-top: 12px; }
    @media print {
      body { padding: 0; }
      @page { margin: 1.5cm; }
    }
  </style>
</head>
<body>
  <div class="header">
    <h1>${isUrdu ? 'کھاتہ مینیجر - گاہک حساب سلپ' : 'Khata Manager - Customer Statement'}</h1>
    <p>${new Date().toLocaleDateString()}</p>
  </div>
  <div class="customer-box">
    <div>
      <p><strong>${isUrdu ? 'گاہک کا نام:' : 'Customer Name:'}</strong> ${customer.name}</p>
      <p><strong>${isUrdu ? 'فون نمبر:' : 'Phone:'}</strong> ${customer.phone}</p>
      ${customer.note ? `<p><strong>${isUrdu ? 'نوٹ:' : 'Note:'}</strong> ${customer.note}</p>` : ''}
    </div>
    <div class="balance-box">
      <p>${isUrdu ? 'موجودہ بقایا:' : 'Current Balance:'}</p>
      <strong>${money(currentBalance, currencyLabel)}</strong>
    </div>
  </div>

  <table>
    <thead>
      <tr>
        <th>${isUrdu ? 'تاریخ' : 'Date'}</th>
        <th>${isUrdu ? 'اندراج / تفصیل' : 'Type / Details'}</th>
        <th>${isUrdu ? 'رقم' : 'Amount'}</th>
        <th>${isUrdu ? 'بقایا' : 'Balance'}</th>
      </tr>
    </thead>
    <tbody>
      ${history.map(h => `
        <tr>
          <td>${localDate(h.transaction.date, isUrdu ? 'ur' : 'en')}</td>
          <td>
            <strong>${h.transaction.kind === 'credit' ? (isUrdu ? 'ادھار دیا' : 'Udhaar Diya') : (isUrdu ? 'وصولی ملی' : 'Payment Mili')}</strong>
            ${h.transaction.items && h.transaction.items.length ? `<br><small style="color: #555;">${h.transaction.items.map(i => `${i.name}${i.qty ? ` (${i.qty})` : ''}`).join(', ')}</small>` : ''}
            ${h.transaction.note ? `<br><small style="color: #777;">${h.transaction.note}</small>` : ''}
          </td>
          <td class="${h.transaction.kind === 'credit' ? 'amount-credit' : 'amount-payment'}">
            ${h.transaction.kind === 'credit' ? '+' : '−'} ${money(h.transaction.amountPaisa, currencyLabel)}
          </td>
          <td>${money(h.balancePaisa, currencyLabel)}</td>
        </tr>
      `).join('')}
    </tbody>
  </table>

  <div class="summary-table">
    <div>
      <p>${isUrdu ? 'کل ادھار:' : 'Total Credit:'} <strong>${money(totalCredit, currencyLabel)}</strong></p>
      <p>${isUrdu ? 'کل وصولی:' : 'Total Received:'} <strong>${money(totalPayment, currencyLabel)}</strong></p>
    </div>
    <div style="text-align: end;">
      <p>${isUrdu ? 'صاف بقایا:' : 'Net Balance:'} <strong style="font-size: 18px; color: #086b57;">${money(currentBalance, currencyLabel)}</strong></p>
    </div>
  </div>

  <div class="footer">
    <p>${isUrdu ? 'کھاتہ مینیجر کے ذریعے تیار کردہ' : 'Generated by Khata Manager'}</p>
  </div>
  <script>
    window.onload = function() { window.print(); };
  </script>
</body>
</html>`;

    printWindow.document.open();
    printWindow.document.write(html);
    printWindow.document.close();
    return true;
  } catch {
    return false;
  }
}
